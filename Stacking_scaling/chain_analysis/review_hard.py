"""
Per-level review sheet of the hard levels of puzzles_50: for every level the
parts on the board, the answer (checked through the game rules) and what
every wrong move does, so a person can sign the tier off level by level.

    python -m chain_analysis.review_hard > REVIEW.md
"""

from __future__ import annotations

import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def fluidnet(d: str) -> list:
    from type_3.game_core import GameState
    from type_3.loader import load_level_from_json
    from type_3.propagation import propagate_fluid
    from type_3.solver import order_by_flow, solve
    from type_3.difficulty import outcome
    spec = load_level_from_json(os.path.join(d, "level.json"))
    sol = order_by_flow(spec, solve(spec))
    lose, win, _ = outcome(spec, set(sol))
    out = [f"- pumps {[(p, spec.cells[p].color) for p in spec.sources]}; "
           f"tanks {[(t, spec.cells[t].color) for t in spec.targets]}; "
           f"red cells {list(spec.protected)}",
           f"- answer (open in this order): {sol} -> {'win' if win and not lose else 'NOT A WIN'}"]
    for v in spec.valves:
        if v in sol:
            continue
        st = GameState(spec=spec, opened_valves=set(sol) | {v})
        out.append(f"  - trap {v}: with the answer open -> {propagate_fluid(st).code.value}")
    return out


def domino(d: str) -> list:
    from type_3_1.cascade import simulate_push
    from type_3_1.difficulty import _frontier, _state_with, outcome, start_of
    from type_3_1.game_core import PieceType
    from type_3_1.loader import load_level_from_json
    spec = load_level_from_json(os.path.join(d, "level.json"))
    S = frozenset(tuple(p) for p in spec.meta["solution_patches"])
    push = spec.meta["origin_dir"]
    kinds = {}
    for pt, pos in spec.fixed_pieces:
        kinds.setdefault(pt.value, []).append(pos)
    st = _state_with(spec, S)
    simulate_push(st, start_of(spec), push)
    out = [f"- START {start_of(spec)}; goals {kinds.get('G', [])}; red {kinds.get('P', [])}; "
           f"splitters {len(kinds.get('T', []))}; step blocks {len(kinds.get('B', []))}",
           f"- answer: patches {sorted(S)}, push {push} -> {outcome(st)}"]
    for b in _frontier(st):
        s2 = _state_with(spec, S | {b})
        simulate_push(s2, start_of(spec), push)
        reds = [p.pos for p in s2.anchors() if p.type == PieceType.PROTECTED and p.toppled]
        out.append(f"  - the answer's wave also stops before {b}; one patch more there -> "
                   f"{outcome(s2)}" + (f", red toppled {reds} (a decoy gap)" if reds
                                      else " (open floor past a goal; no spare patch exists)"))
    for dd in ("+x", "-x", "+y", "-y"):
        if dd == push:
            continue
        s3 = _state_with(spec, S)
        simulate_push(s3, start_of(spec), dd)
        out.append(f"  - push {dd} instead -> {outcome(s3)}")
    return out


def pipefit(d: str) -> list:
    import dataclasses
    from type_2_3.difficulty import analyze
    from type_2_3.game_core import init_state
    from type_2_3.loader import load_level_from_json
    from type_2_3.mechanics import step_place, submit
    from type_2_3.solver import solve
    spec = load_level_from_json(os.path.join(d, "level.json"))
    plan = solve(spec)
    st = init_state(spec)
    for p in plan:
        step_place(st, p.type, p.pos, p.orientation)
    res = submit(st).code.value
    m = analyze(spec)
    out = [f"- entrance {list(spec.entrances)}; exits {list(spec.exits)}; "
           f"obstacles {list(spec.obstacles)}; stock { {pt.value: n for pt, n in spec.inventory.items() if n} }",
           f"- answer: {len(plan)} pieces -> {res}; {m['n_solutions']} networks fit; "
           f"staircase route {'works' if m['staircase_ok'] else 'fails'}"]
    for o in spec.obstacles:
        rest = [c for c in spec.obstacles if c != o]
        m2 = analyze(dataclasses.replace(spec, obstacles=rest, obstacle_shapes=[[c] for c in rest]))
        out.append(f"  - without obstacle {o}: {m2['n_solutions']} networks, staircase "
                   f"{'works' if m2['staircase_ok'] else 'fails'}")
    return out


def main() -> None:
    print("# Hard levels: per-level review\n")
    print("Generated by `python -m chain_analysis.review_hard`; every outcome is "
          "computed through the game rules.\n")
    for game, name, fn in (("type_3", "FluidNet", fluidnet), ("type_3_1", "Domino", domino),
                           ("type_2_3", "PipeFit", pipefit)):
        print(f"## {name}\n")
        for d in sorted(glob.glob(os.path.join(game, "puzzles_50", "*_hard_*"))):
            print(f"### {os.path.basename(d)}\n")
            print("\n".join(fn(d)) + "\n")


if __name__ == "__main__":
    main()
